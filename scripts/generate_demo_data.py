VENDOR_FOR_PRODUCT = (("ST", "SEAGATE"), ("HUC", "HGST"), ("NV", "SAMPLE"))


def _digest(*parts: str) -> bytes:
    return hashlib.sha256("|".join(parts).encode("utf-8")).digest()


def stable_serial(bench: str, slot: str, original: str) -> str:
    """Deterministic fake serial for one bench slot, shaped like ``original``."""
    template = original.strip().upper()
    if not re.fullmatch(r"[A-Z0-9-]{6,16}", template) or "MOCK" in template:
        template = "SSSDDDDDDSSD"
    digest = _digest("serial", bench, slot)
    letters = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    out = []
    for index, char in enumerate(template):
        byte = digest[index % len(digest)] ^ index
        if char.isdigit():
            out.append(str(byte % 10))
        elif char.isalpha():
            out.append(letters[byte % len(letters)])
        else:
            out.append(char)
    serial = "".join(out)
    if serial == original.strip().upper():
        serial = "D" + serial[1:]
    return serial


def _stable_int(bench: str, slot: str, label: str, bits: int) -> int:
    return int.from_bytes(_digest(label, bench, slot)[:8], "big") % (1 << bits)


def _collect_serial_tokens(payload: dict[str, Any]) -> set[str]:
    """Every string in the fixture that is (or embeds) the drive serial."""
    tokens: set[str] = set()
    serial = str(payload.get("serial_number") or "").strip()
    if serial:
        tokens.add(serial)
    nvme_cli = payload.get("nvme_cli") or {}
    sn = str(((nvme_cli.get("id_ctrl") or {}).get("sn")) or "").strip()
    if sn:
        tokens.add(sn)
    for device in (nvme_cli.get("list") or {}).get("Devices") or []:
        value = str((device or {}).get("SerialNumber") or "").strip()
        if value:
            tokens.add(value)
    return {token for token in tokens if len(token) >= 4}


def _walk(obj: Any, fn: Callable[[str, Any], Any]) -> Any:
    if isinstance(obj, dict):
        return {key: fn(key, _walk(value, fn)) for key, value in obj.items()}
    if isinstance(obj, list):
        return [_walk(value, fn) for value in obj]
    return obj


def anonymize_fixture(payload: dict[str, Any], bench: str, slot: str) -> dict[str, Any]:
    """Copy of a smartctl fixture with serials/IDs replaced and the slot renamed."""
    from cdi_health.classes.mock_export import deep_replace_str

    data = copy.deepcopy(payload)
    original_serial = str(data.get("serial_number") or "")
    new_serial = stable_serial(bench, slot, original_serial or "SERIAL0000")
    for token in sorted(_collect_serial_tokens(data), key=len, reverse=True):
        data = deep_replace_str(data, token, new_serial)
    data["serial_number"] = new_serial

    def scrub_ids(key: str, value: Any) -> Any:
        if key == "wwn" and isinstance(value, dict):
            return {**value, "id": _stable_int(bench, slot, "wwn", 36)}
        if key == "eui64" and isinstance(value, dict):
            return {**value, "ext_id": _stable_int(bench, slot, "eui64", 40)}
        if key in ("fguid", "nguid") and isinstance(value, str) and value.strip("0-"):
            return str(uuid.UUID(bytes=_digest(key, bench, slot)[:16]))
        if key == "logical_unit_id" and isinstance(value, str):
            return f"0x5000c500{_stable_int(bench, slot, 'lu', 32):08x}"
        return value

    data = _walk(data, scrub_ids)

    # Fixture vendor placeholder → the product's real OEM (or a neutral name).
    def fix_vendor(text: str) -> str:
        match = re.match(r"^REVERT\s+(\S+)", text)
        if not match:
            return text
        product = match.group(1)
        vendor = next((v for prefix, v in VENDOR_FOR_PRODUCT if product.startswith(prefix)), "SAMPLE")
        return f"{vendor} {product}"

    for key in ("model_name", "model_family"):
        if isinstance(data.get(key), str):
            data[key] = fix_vendor(data[key])
    if data.get("vendor") == "REVERT":
        product = str(data.get("product") or "")
        data["vendor"] = next((v for prefix, v in VENDOR_FOR_PRODUCT if product.startswith(prefix)), "SAMPLE")

    # Put the drive in its demo slot (device.name drives the record's dut).
    old_name = str((data.get("device") or {}).get("name") or "")
    if old_name and old_name != slot:
        pattern = re.compile(re.escape(old_name) + r"(?!\d)")
        data = _walk(data, lambda _k, v: pattern.sub(slot, v) if isinstance(v, str) else v)
        data["device"]["name"] = slot
        if "info_name" in data["device"]:
            data["device"]["info_name"] = pattern.sub(slot, str(data["device"]["info_name"]))
    return data


