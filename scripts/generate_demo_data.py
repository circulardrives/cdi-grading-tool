def scsi_names(payload: dict[str, Any]) -> None:
    """Add the ``scsi_vendor`` / ``scsi_model_name`` keys smartctl 7.3+ emits (older fixtures lack them)."""
    if str((payload.get("device") or {}).get("protocol") or "").upper() != "SCSI":
        return
    vendor = str(payload.get("vendor") or "").strip()
    product = str(payload.get("product") or "").strip()
    if vendor and product:
        payload.setdefault("scsi_vendor", vendor)
        payload.setdefault("scsi_product", product)
        payload.setdefault("scsi_model_name", f"{vendor} {product}")
        if payload.get("revision"):
            payload.setdefault("scsi_revision", payload["revision"])


def older_by(hours: int) -> Mutator:
    """The same drive ``hours`` power-on hours earlier (for older saved scans)."""

    def mutate(payload: dict[str, Any]) -> None:
        pot = payload.get("power_on_time")
        if isinstance(pot, dict) and isinstance(pot.get("hours"), int):
            pot["hours"] = max(pot["hours"] - hours, 0)
        nvme = payload.get("nvme_smart_health_information_log")
        if isinstance(nvme, dict) and isinstance(nvme.get("power_on_hours"), int):
            nvme["power_on_hours"] = max(nvme["power_on_hours"] - hours, 0)
        for entry in (payload.get("ata_smart_attributes") or {}).get("table") or []:
            if entry.get("id") == 9 and isinstance(entry.get("raw"), dict):
                raw = entry["raw"]
                if isinstance(raw.get("value"), int):
                    raw["value"] = max(raw["value"] - hours, 0)
                    raw["string"] = str(raw["value"])

    return mutate


