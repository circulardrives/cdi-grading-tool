"""
Generate the sample data behind the static dashboard demo (``VITE_DEMO=1``).

Run from the repository root (``scripts/build-demo.sh`` does this for you)::

    PYTHONPATH=src python scripts/generate_demo_data.py

Every drive comes from a smartctl-JSON fixture in the repo
(``src/cdi_health/mock_data`` and ``tests/fixtures/revert_standard``), is
anonymized (serials, WWN / EUI-64 / FGUID, vendor strings), and then goes
through the real pipeline: ``create_mock_device`` → the API's scoring
enrichment → the real API endpoints (machines, fleet, CSV, history, reports)
served in-process with FastAPI's TestClient. Grades and reasons are therefore
exactly what CDI Health produces for those drives.

Output (committed; regenerate after grading changes):

- ``dashboard/apps/web/src/demo/data/*.json``  API responses the demo serves
- ``dashboard/apps/web/src/demo/data/files/*`` pre-rendered report / CSV files

Serials are derived from a hash of bench + slot, and every timestamp is
fixed, so a rebuild with unchanged grading produces identical files.
"""

