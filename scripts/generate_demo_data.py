def grade_bench(bench: dict[str, Any], scanned_at: datetime, swaps: dict[str, Path] | None = None) -> dict[str, Any]:
    """Scan one bench's fixtures through the API's scoring path; returns a ScanResponse dict."""
    from cdi_health.api.services import _enrich_devices_with_scores, build_threshold_config, summarize_devices
    from cdi_health.classes.mock import create_mock_device

    swaps = swaps or {}
    raw_devices = []
    for slot, path, mutators in bench["drives"]:
        source = swaps.get(slot, path)
        payload = json.loads(source.read_text(encoding="utf-8"))
        payload = anonymize_fixture(payload, bench["key"], slot)
        scsi_names(payload)
        for mutate in mutators:
            mutate(payload)
        if scanned_at != LATEST_SCAN_AT[bench["key"]]:
            older_by(int((LATEST_SCAN_AT[bench["key"]] - scanned_at).total_seconds() // 3600))(payload)
        device = create_mock_device(mock_data=payload, device_id=slot).to_dict(pop=True)
        raw_devices.append({k: v for k, v in device.items() if not k.startswith("_")})

    threshold_config = build_threshold_config()
    devices = _enrich_devices_with_scores(raw_devices, threshold_config)
    stamp = scanned_at.isoformat(timespec="seconds")
    for device in devices:
        device["scan_timestamp"] = stamp
    return {
        "scanned_at": stamp,
        "grading_profile": threshold_config.grading_profile,
        "summary": summarize_devices(devices),
        "devices": devices,
    }


class _FrozenDatetime(datetime):
    @classmethod
    def now(cls, tz=None):  # noqa: D102
        frozen = GENERATED_AT
        return frozen.astimezone(tz) if tz else frozen.replace(tzinfo=None)


def _freeze_clock() -> None:
    """Pin every ``now()`` the API and reporter use, so output is reproducible."""
    import cdi_health.api.app as app_module
    import cdi_health.api.history as history_module
    import cdi_health.api.machines as machines_module
    import cdi_health.api.services as services_module
    import cdi_health.classes.reporter as reporter_module

    for module in (app_module, machines_module, services_module, reporter_module):
        module.datetime = _FrozenDatetime

    counter = iter(range(1, 10_000))

    def fake_uuid4() -> uuid.UUID:
        return uuid.uuid5(ID_NAMESPACE, f"id-{next(counter)}")

    fake_uuid = SimpleNamespace(uuid4=fake_uuid4, UUID=uuid.UUID)
    machines_module.uuid = fake_uuid
    history_module.uuid = fake_uuid


def _package_version() -> str:
    """Latest released version from CHANGELOG.md (installed metadata may be stale)."""
    for line in (REPO_ROOT / "CHANGELOG.md").read_text(encoding="utf-8").splitlines():
        match = re.match(r"^## \[(\d+\.\d+\.\d+)\]", line)
        if match:
            return match.group(1)
    return "0.0.0"


def _slim(device: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in device.items() if k not in HISTORY_DROP_FIELDS}


def _write_file(path: Path, content: bytes) -> None:
    """Write a report/CSV with LF endings and no trailing spaces (the repo's pre-commit style)."""
    lines = content.replace(b"\r\n", b"\n").split(b"\n")
    text = b"\n".join(line.rstrip(b" \t") for line in lines).rstrip(b"\n") + b"\n"
    path.write_bytes(text)


def _write_json(name: str, payload: Any) -> int:
    path = OUT_DIR / name
    text = json.dumps(payload, indent=1, sort_keys=False, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8")
    return len(text.encode("utf-8"))


def selftest_status(scan: dict[str, Any], machine_id: str) -> dict[str, Any]:
    """GET /selftests/status as a bench answers it: one row per responding NVMe controller."""
    from cdi_health.classes.nvme_selftest import RESULT_STRINGS, SELF_TEST_CODE_STRINGS

    rows = []
    for device in scan["devices"]:
        dut = str(device.get("dut") or "")
        if not dut.startswith("/dev/nvme") or device.get("grading_status") == "UNGRADED":
            # A dead controller doesn't answer nvme-cli: it is simply not listed.
            continue
        log = device.get("nvme_self_test_log") or {}
        entries = []
        for entry in (log.get("table") or [])[:5]:
            result = int(((entry.get("self_test_result") or {}).get("value")) or 0)
            code = int(((entry.get("self_test_code") or {}).get("value")) or 1)
            entries.append(
                {
                    "result_code": result,
                    "result": RESULT_STRINGS.get(result, f"Reserved ({result})"),
                    "test_type_code": code,
                    "test_type": SELF_TEST_CODE_STRINGS.get(code, f"Unknown ({code})"),
                    "completion_time": int(entry.get("power_on_hours") or 0),
                }
            )
        latest = entries[0] if entries else None
        rows.append(
            {
                "device": dut,
                "supported": True,
                "status": "No self-test in progress",
                "in_progress": False,
                "passed": bool(latest and latest["result_code"] == 0),
                "failed": bool(latest and latest["result_code"] in (5, 6, 7)),
                "aborted": bool(latest and latest["result_code"] in (1, 2, 3, 4, 8, 9)),
                "last_test_date": None,
                "error": None,
                "latest_result": latest,
                "recent_results": entries,
                "current_completion": 0,
                "current_operation": "No self-test in progress",
                "logs_message": None if entries else "No completed self-test entries in NVMe Log Page 0x06.",
            }
        )
    return {"devices": rows, "total": len(rows), "machine_id": machine_id}


def main() -> int:
    os.environ["TZ"] = "UTC"
    time.tzset()
    work = Path(tempfile.mkdtemp(prefix="cdi-demo-"))
    os.environ["CDI_HEALTH_DATA_DIR"] = str(work)
    os.environ["CDI_HEALTH_API_NO_AUTH"] = "1"
    os.environ.pop("CDI_HEALTH_API_TOKEN", None)
    os.environ.pop("CDI_HEALTH_API_MOCK_DATA", None)

    import logging

    logging.disable(logging.WARNING)

    from fastapi.testclient import TestClient

    from cdi_health.api.app import create_app
    from cdi_health.api.schemas import ScanResponse

    _freeze_clock()
    version = _package_version()
    app = create_app()
    runtime = app.state.runtime
    client = TestClient(app)

    try:
        # Register benches the way a check leaves them: reachable, lab (no-auth) mode.
        machine_ids: dict[str, str] = {}
        for bench in BENCHES:
            machine = runtime.machine_store.create_machine(
                {
                    "name": bench["key"],
                    "hostname": bench["hostname"],
                    "address": bench["address"],
                    "location": bench["location"],
                    "notes": bench["notes"],
                }
            )
            machine_ids[bench["key"]] = machine["id"]
            runtime.machine_store.set_status(
                machine["id"],
                "reachable",
                seen=True,
                remote_version=version,
                remote_auth="none",
                remote_hostname=bench["key"],
            )

        # Record scans oldest first, exactly as a forwarded remote scan is stored.
        scans: list[tuple[datetime, dict[str, Any], dict[str, Path]]] = []
        by_key = {bench["key"]: bench for bench in BENCHES}
        for key, days, swaps in EARLIER_SCANS:
            scans.append((LATEST_SCAN_AT[key] - timedelta(days=days), by_key[key], swaps))
        for bench in BENCHES:
            scans.append((LATEST_SCAN_AT[bench["key"]], bench, {}))
        scans.sort(key=lambda item: item[0])

        latest: dict[str, dict[str, Any]] = {}
        for scanned_at, bench, swaps in scans:
            result = grade_bench(bench, scanned_at, swaps)
            machine_id = machine_ids[bench["key"]]
            result = ScanResponse.model_validate(
                {**result, "machine_id": machine_id, "executed_on": "remote", "remote_address": bench["address"]}
            ).model_dump(mode="json")
            runtime.machine_store.record_scan(machine_id, result, success=True)
            runtime.history_store.record_scan(
                {**result, "devices": [_slim(d) for d in result["devices"]]},
                machine_id=machine_id,
                mock=False,
            )
            latest[bench["key"]] = result

        def get(path: str) -> Any:
            response = client.get(path)
            response.raise_for_status()
            return response

        machines = get("/api/v1/machines").json()
        fleet = get("/api/v1/fleet/devices").json()
        history = get("/api/v1/history?limit=500").json()
        history_details = {entry["id"]: get(f"/api/v1/history/{entry['id']}").json() for entry in history}

        # Pre-rendered files: the fleet report and each bench's latest saved
        # scan as a report (HTML + CSV), plus the drive-list CSVs.
        if FILES_DIR.exists():
            shutil.rmtree(FILES_DIR)
        FILES_DIR.mkdir(parents=True)
        latest_history: dict[str, str] = {}
        for entry in history:  # newest first
            latest_history.setdefault(entry["machine_id"], entry["id"])
        report_jobs = [("fleet", {"source": "fleet"})] + [
            (key, {"source": "history", "history_ids": [latest_history[machine_ids[key]]]}) for key in machine_ids
        ]
        report_files: dict[str, dict[str, str]] = {}
        for scope, body in report_jobs:
            for fmt in ("html", "csv"):
                response = client.post(
                    "/api/v1/reports",
                    json={**body, "format": fmt, "output_file": f"cdi-report-demo-{scope}.{fmt}"},
                )
                response.raise_for_status()
                record = response.json()
                content = get(f"/api/v1/reports/{record['filename']}").content
                if fmt == "html":
                    # The demo makes no network requests: drop the web-font import
                    # (the report falls back to its system font stack).
                    content = re.sub(rb"\s*@import url\([^)]*fonts\.googleapis\.com[^)]*\);", b"", content)
                _write_file(FILES_DIR / record["filename"], content)
                report_files.setdefault(machine_ids.get(scope, "fleet"), {})[fmt] = record["filename"]
        # "Recent reports" starts with the fleet report and one bench report.
        shown = {"cdi-report-demo-fleet.html", "cdi-report-demo-fleet.csv", "cdi-report-demo-bench-02.html"}
        reports = [entry for entry in get("/api/v1/reports").json() if entry["filename"] in shown]

        csv_files = {}
        for scope, machine_id in [("all", None)] + [(key, machine_ids[key]) for key in machine_ids]:
            query = f"?machine_id={machine_id}" if machine_id else ""
            response = get(f"/api/v1/fleet/devices.csv{query}")
            match = re.search(r'filename="([^"]+)"', response.headers.get("content-disposition", ""))
            filename = match.group(1) if match else f"cdi-drives-{scope}.csv"
            _write_file(FILES_DIR / filename, response.content)
            csv_files[machine_id or "all"] = filename

        selftests = {machine_ids[key]: selftest_status(scan, machine_ids[key]) for key, scan in latest.items()}

        health = {
            "status": "ok",
            "version": version,
            "hostname": "demo",
            "is_root": True,
            "allow_non_root_mode": False,
            "api_token_enabled": False,
            "auth_mode": "none",
            "missing_required_tools": [],
            "weasyprint_available": False,
            "message": None,
        }

        sizes = {
            "health.json": _write_json("health.json", {"_comment": COMMENT, **health}),
            "machines.json": _write_json("machines.json", {"_comment": COMMENT, "machines": machines}),
            "fleet.json": _write_json("fleet.json", {"_comment": COMMENT, **fleet}),
            "history.json": _write_json(
                "history.json",
                {"_comment": COMMENT, "summaries": history, "details": history_details},
            ),
            "reports.json": _write_json("reports.json", {"_comment": COMMENT, "reports": reports}),
            "selftests.json": _write_json("selftests.json", {"_comment": COMMENT, "benches": selftests}),
            "files.json": _write_json(
                "files.json",
                {
                    "_comment": COMMENT,
                    "generated_at": GENERATED_AT.isoformat(),
                    "drives_csv": csv_files,
                    "reports": report_files,
                },
            ),
        }
    finally:
        shutil.rmtree(work, ignore_errors=True)

    grades: dict[str, int] = {}
    for device in fleet["devices"]:
        grade = str(device.get("health_grade"))
        grades[grade] = grades.get(grade, 0) + 1
    total = sum(sizes.values()) + sum(p.stat().st_size for p in FILES_DIR.iterdir())
    print(f"Wrote demo data to {OUT_DIR.relative_to(REPO_ROOT)} ({total / 1024:.0f} KiB)")
    for name, size in sizes.items():
        print(f"  {name:16} {size / 1024:7.0f} KiB")
    print(f"  files/           {', '.join(sorted(p.name for p in FILES_DIR.iterdir()))}")
    print(f"Grades: {dict(sorted(grades.items()))}")
    return 0


